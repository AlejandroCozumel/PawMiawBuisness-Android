#!/usr/bin/env python3
"""Lucide icons for PawMiaw Business Android, the same set the iOS app ships.

Reads the iOS app's generated icons (../PawMiawNegocios: Assets.xcassets/Lucide/*.svg
and Design/GlyphNames.swift, made by its scripts/lucide-icons.py from the web's
lucide-react) and writes design/LucideData.kt (each icon as SVG path data, every
element turned into a path) and design/GlyphNames.kt (SF Symbol → Lucide, aliases).
Run from the repo root:  python3 scripts/lucide-icons.py ../PawMiawNegocios
"""
import os, re, sys, glob
from xml.etree import ElementTree as ET

IOS = sys.argv[1] if len(sys.argv) > 1 else '../PawMiawNegocios'
ASSETS = os.path.join(IOS, 'PawMiawNegocios/Assets.xcassets/Lucide')
NAMES = os.path.join(IOS, 'PawMiawNegocios/Design/GlyphNames.swift')
OUT = 'app/src/main/java/com/pawmiaw/business/design'

def num(v, d=0.0):
    try: return float(v)
    except (TypeError, ValueError): return d

def f(x):
    s = ('%.3f' % x).rstrip('0').rstrip('.')
    return s if s not in ('-0', '') else '0'

def rect(a):
    x, y, w, h = num(a.get('x')), num(a.get('y')), num(a.get('width')), num(a.get('height'))
    rx = a.get('rx'); ry = a.get('ry')
    rx = num(rx if rx is not None else ry); ry = num(ry if ry is not None else rx)
    rx = min(rx, w / 2); ry = min(ry, h / 2)
    if rx <= 0:
        return f'M{f(x)} {f(y)}H{f(x+w)}V{f(y+h)}H{f(x)}Z'
    return (f'M{f(x+rx)} {f(y)}H{f(x+w-rx)}A{f(rx)} {f(ry)} 0 0 1 {f(x+w)} {f(y+ry)}'
            f'V{f(y+h-ry)}A{f(rx)} {f(ry)} 0 0 1 {f(x+w-rx)} {f(y+h)}'
            f'H{f(x+rx)}A{f(rx)} {f(ry)} 0 0 1 {f(x)} {f(y+h-ry)}'
            f'V{f(y+ry)}A{f(rx)} {f(ry)} 0 0 1 {f(x+rx)} {f(y)}Z')

def ellipse(cx, cy, rx, ry):
    return (f'M{f(cx-rx)} {f(cy)}A{f(rx)} {f(ry)} 0 1 0 {f(cx+rx)} {f(cy)}'
            f'A{f(rx)} {f(ry)} 0 1 0 {f(cx-rx)} {f(cy)}Z')

def points(p):
    vals = [float(v) for v in re.split(r'[\s,]+', p.strip()) if v]
    pairs = list(zip(vals[0::2], vals[1::2]))
    return 'M' + 'L'.join(f'{f(a)} {f(b)}' for a, b in pairs)

def to_path(el):
    tag = el.tag.split('}')[-1]; a = el.attrib
    if tag == 'path': return a.get('d')
    if tag == 'rect': return rect(a)
    if tag == 'circle': return ellipse(num(a.get('cx')), num(a.get('cy')), num(a.get('r')), num(a.get('r')))
    if tag == 'ellipse': return ellipse(num(a.get('cx')), num(a.get('cy')), num(a.get('rx')), num(a.get('ry')))
    if tag == 'line': return f"M{f(num(a.get('x1')))} {f(num(a.get('y1')))}L{f(num(a.get('x2')))} {f(num(a.get('y2')))}"
    if tag == 'polyline': return points(a.get('points', ''))
    if tag == 'polygon': return points(a.get('points', '')) + 'Z'
    return None

icons = {}
for folder in sorted(glob.glob(os.path.join(ASSETS, 'lucide-*.imageset'))):
    name = os.path.basename(folder)[len('lucide-'):-len('.imageset')]
    svg = glob.glob(os.path.join(folder, '*.svg'))[0]
    root = ET.parse(svg).getroot()
    paths = [p for p in (to_path(el) for el in root.iter() if el is not root) if p]
    icons[name] = paths

names_src = open(NAMES).read()
def swift_map(label):
    block = names_src[names_src.index(label):]
    block = block[block.index('['):block.index('\n    ]')]
    return re.findall(r'"([^"]+)":\s*"([^"]+)"', block)
sf = swift_map('static let sf')
# SF Symbols iOS draws itself (no Lucide twin in the iOS map): the closest Lucide icon.
sf += [('allergens', 'thermometer')]
aliases = swift_map('static let aliases')

def kstr(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'

items = sorted(icons.items())
chunks = [items[i:i+60] for i in range(0, len(items), 60)]
out = ['// Generated by scripts/lucide-icons.py — do not edit by hand.', '// Lucide icons (ISC licence, assets/licenses/Lucide-LICENSE.txt) as SVG path data on a 24 grid.',
       'package com.pawmiaw.business', '', 'object LucideData {',
       '    val icons: Map<String, Array<String>> by lazy {', '        HashMap<String, Array<String>>(%d).apply {' % (len(items) * 2)]
out += [f'            part{i}(this)' for i in range(len(chunks))]
out += ['        }', '    }', '']
for i, chunk in enumerate(chunks):
    out.append(f'    private fun part{i}(m: HashMap<String, Array<String>>) {{')
    for name, paths in chunk:
        out.append(f'        m[{kstr(name)}] = arrayOf(' + ', '.join(kstr(p) for p in paths) + ')')
    out.append('    }')
out += ['}', '']
open(os.path.join(OUT, 'LucideData.kt'), 'w').write('\n'.join(out))

g = ['// Generated by scripts/lucide-icons.py — do not edit by hand.', '// The SF Symbol names the iOS screens use, mapped to the web\'s Lucide icons (same as iOS GlyphNames.swift).',
     'package com.pawmiaw.business', '', 'object GlyphNames {',
     '    /** SF Symbol (without ".fill") → Lucide. */', '    val sf: Map<String, String> = hashMapOf(']
g += [f'        {kstr(k)} to {kstr(v)},' for k, v in sf]
g += ['    )', '', '    /** Older Lucide names → the icon in the catalog. */', '    val aliases: Map<String, String> = hashMapOf(']
g += [f'        {kstr(k)} to {kstr(v)},' for k, v in aliases]
g += ['    )', '}', '']
open(os.path.join(OUT, 'GlyphNames.kt'), 'w').write('\n'.join(g))
print(f'{len(icons)} icons, {len(sf)} SF names, {len(aliases)} aliases')
